/**
 * The icon step of a package build. A package that draws icons without React
 * names them in its manifest (`mapcairn.icons`: the development dependency
 * they come from and the file names), and this writes their paths into one
 * committed module, `src/lit/icons.generated.ts`, so the package ships path
 * data and no icon runtime.
 *
 *   npm run icons:write
 *
 * The module is committed because tests and the host read the package's source
 * before anything is built. The package build fails when it differs from what
 * the dependency draws, and writes the notices file with the dependency's
 * licence, which the copied paths carry with them.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { assertBundledLicences, noticesOf } from "./bundleLicences.mjs";
import { isEntryPoint } from "./entryPoint.mjs";
import { ALLOWLIST_FILE } from "./sdkLicences.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The generated module, from the package's folder. */
export const ICON_MODULE = "src/lit/icons.generated.ts";

/** The one weight every icon is drawn in (DESIGN.md, "Components"). */
const ICON_WEIGHT = "regular";

/** An icon file this step can copy whole: one `svg` holding one plain path. */
const ONE_PATH_SVG =
  /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="([\d .-]+)" fill="currentColor"><path d="([A-Za-z\d .,-]+)"\/><\/svg>$/;

/**
 * @typedef {object} IconSettings
 * @property {string} from The development dependency that draws the icons.
 * @property {string[]} names The icon file names, without weight or ending.
 */

/**
 * What a manifest says about the icons its package copies.
 *
 * @param {Record<string, any>} manifest
 * @returns {IconSettings | undefined} `undefined` for a package that copies none.
 */
export function iconSettingsOf(manifest) {
  return manifest.mapcairn?.icons;
}

/**
 * The view box and path of one icon file.
 *
 * @param {string} svg The file's text.
 * @param {string} name The icon, for the message.
 * @returns {{ viewBox: string, path: string }}
 * @throws {Error} When the file holds anything this step would drop.
 */
export function parseIconSvg(svg, name) {
  const match = ONE_PATH_SVG.exec(svg.trim());
  if (match === null) {
    throw new Error(
      `The icon "${name}" is not one svg holding one path, so copying it would lose part of it. Teach parseIconSvg in scripts/icons.mjs what it holds.`,
    );
  }
  return { viewBox: match[1], path: match[2] };
}

/** `arrow-up` as `ARROW_UP_ICON`. */
const constantName = (/** @type {string} */ name) =>
  `${name.replaceAll("-", "_").toUpperCase()}_ICON`;

/**
 * The text of the generated module, laid out as the formatter leaves it.
 *
 * @param {readonly string[]} names
 * @param {(name: string) => string} readSvg The text of an icon's file.
 * @returns {string}
 */
export function iconModuleSource(names, readSvg) {
  const constants = names.map((name) => {
    const icon = parseIconSvg(readSvg(name), name);
    return [
      `/** The \`${name}\` icon. */`,
      `export const ${constantName(name)} = {`,
      `  viewBox: "${icon.viewBox}",`,
      `  path: "${icon.path}",`,
      "} as const;",
    ].join("\n");
  });
  return [
    "// SPDX-License-Identifier: AGPL-3.0-only",
    "// Copyright MapCairn contributors",
    "// Generated by scripts/icons.mjs (`npm run icons:write`): do not edit.",
    "// The paths are from Phosphor Icons, MIT: see THIRD-PARTY-NOTICES.md.",
    "",
    constants.join("\n\n"),
    "",
  ].join("\n");
}

/**
 * The folder of the icon dependency, as the package that copies from it finds it.
 *
 * @param {string} folder The package folder.
 * @param {string} from The dependency's name.
 * @returns {string}
 * @throws {Error} When it is not installed.
 */
export function iconPackageFolder(folder, from) {
  const found = createRequire(path.join(folder, "package.json"))
    .resolve.paths(from)
    ?.map((parent) => path.join(parent, from))
    .find((candidate) => existsSync(path.join(candidate, "package.json")));
  if (found === undefined) {
    throw new Error(`${from}, which draws the icons, is not installed.`);
  }
  return found;
}

/**
 * What the icon step makes for one package: the module's text and the notices.
 *
 * @param {string} folder The package folder.
 * @param {Parameters<typeof assertBundledLicences>[1]} allowlist
 * @returns {{ module: string, notices: string }}
 * @throws {Error} When an icon cannot be copied or its licence is not allowed.
 */
export function iconStep(folder, allowlist) {
  const manifest = JSON.parse(
    readFileSync(path.join(folder, "package.json"), "utf8"),
  );
  const settings = iconSettingsOf(manifest);
  if (settings === undefined) {
    throw new Error(`${manifest.name} names no icons in mapcairn.icons.`);
  }
  const directory = iconPackageFolder(folder, settings.from);
  const source = JSON.parse(
    readFileSync(path.join(directory, "package.json"), "utf8"),
  );
  const copied = [
    {
      name: source.name,
      version: source.version,
      licence: source.license,
      directory,
    },
  ];
  assertBundledLicences(copied, allowlist);
  return {
    module: iconModuleSource(settings.names, (name) =>
      readFileSync(
        path.join(directory, "assets", ICON_WEIGHT, `${name}.svg`),
        "utf8",
      ),
    ),
    notices: noticesOf(
      copied,
      allowlist,
      `The icons that \`${manifest.name}\` draws are copied from the package below, under the licence shown.`,
    ),
  };
}

/** The allowlist the notices' licences are judged against. */
const readAllowlist = () =>
  JSON.parse(readFileSync(path.join(REPO, ALLOWLIST_FILE), "utf8"));

/**
 * The step as the package build runs it: fails on a stale module and writes the
 * notices file. A package that copies no icon is left alone.
 *
 * @param {string} folder The package folder.
 * @param {string} noticesFile The notices file's name.
 * @throws {Error} When the committed module is not what the dependency draws.
 */
export function buildIcons(folder, noticesFile) {
  const manifest = JSON.parse(
    readFileSync(path.join(folder, "package.json"), "utf8"),
  );
  if (iconSettingsOf(manifest) === undefined) {
    return;
  }
  const made = iconStep(folder, readAllowlist());
  const committed = path.join(folder, ICON_MODULE);
  if (
    !existsSync(committed) ||
    readFileSync(committed, "utf8") !== made.module
  ) {
    throw new Error(
      `${ICON_MODULE} is not what ${iconSettingsOf(manifest)?.from} draws. Run npm run icons:write and commit it.`,
    );
  }
  writeFileSync(path.join(folder, noticesFile), made.notices);
}

if (isEntryPoint(import.meta.url)) {
  const folder = path.join(REPO, "packages", "map");
  writeFileSync(
    path.join(folder, ICON_MODULE),
    iconStep(folder, readAllowlist()).module,
  );
}

/**
 * Turns an agent definition in `.claude/agents` into the file formats other
 * coding tools read. The substance of an agent is its description and its role
 * text, so that is all that is carried over. Claude's tool list and model
 * name mean nothing to the other tools (and some reject unknown tools), so
 * they are left out and the other tools use their own defaults, except for
 * Antigravity, which needs a tool list and gets the one it documents.
 */
import { claudeOnlyProblems, parseFrontmatter } from "./skills.mjs";

/**
 * @typedef {object} Agent
 * @property {string} name
 * @property {string} description
 * @property {string} body The role text, with leading blank lines removed.
 * @property {string[]} [tools] Claude's tool names, or none when the source
 *   names none (Claude Code then gives the agent every tool).
 */

/**
 * Reads an agent file and checks the fields every tool needs.
 *
 * @param {string} filename The agent's file name, such as `implementer.md`.
 * @param {string} text
 * @returns {Agent}
 */
export function parseAgent(filename, text) {
  const { fields, body, problems: frontmatter } = parseFrontmatter(text);
  const problems = [...frontmatter, ...claudeOnlyProblems(body)];
  if (problems.length > 0) {
    throw new Error(`${filename}: ${problems.join("; ")}`);
  }
  const { name, description } = fields;
  if (!name || !description) {
    throw new Error(`${filename}: name and description are required`);
  }
  const stem = filename.replace(/\.md$/, "");
  if (name !== stem) {
    throw new Error(
      `${filename}: name "${name}" must equal its filename "${stem}"`,
    );
  }
  const tools = fields.tools
    ? fields.tools.split(",").map((tool) => tool.trim())
    : undefined;
  return { name, description, body: body.replace(/^\n+/, ""), tools };
}

/** The line that tells a reader not to edit a generated file. */
const note = (/** @type {Agent} */ agent) =>
  `Generated by \`npm run agents:sync\` from .claude/agents/${agent.name}.md. Edit that file, not this one.`;

/**
 * The opencode format: a subagent with a description and the role text.
 *
 * @param {Agent} agent
 * @returns {string}
 */
export function renderOpencode(agent) {
  return [
    "---",
    `description: ${JSON.stringify(agent.description)}`,
    "mode: subagent",
    "---",
    "",
    `<!-- ${note(agent)} -->`,
    "",
    agent.body,
  ].join("\n");
}

/**
 * Markdown with a name and a description in the frontmatter, then the role
 * text: the shape the Copilot and Qwen Code agent files share.
 *
 * @param {Agent} agent
 * @returns {string}
 */
function renderNamedMarkdown(agent) {
  return [
    "---",
    `name: ${JSON.stringify(agent.name)}`,
    `description: ${JSON.stringify(agent.description)}`,
    "---",
    "",
    `<!-- ${note(agent)} -->`,
    "",
    agent.body,
  ].join("\n");
}

/**
 * The GitHub Copilot custom agent format (`.agent.md`).
 *
 * @param {Agent} agent
 * @returns {string}
 */
export function renderCopilot(agent) {
  return renderNamedMarkdown(agent);
}

/**
 * The Qwen Code subagent format (`.qwen/agents/<name>.md`). Its optional
 * `model`, `tools` and `approvalMode` fields are left out, so the agent
 * inherits the session's model and tools.
 *
 * @param {Agent} agent
 * @returns {string}
 */
export function renderQwen(agent) {
  return renderNamedMarkdown(agent);
}

/**
 * The tool names Antigravity documents for a custom agent, each with the Claude
 * tools it stands for, in the order they are written. They are the only four
 * the documentation names; an unknown name is a known cause of a hung agent, so
 * no other is guessed. Glob and Skill have no documented name: `grep_search` and
 * `run_command` find files, and the role text names the skill to follow (whether
 * Antigravity gives a custom agent the workspace skills is not checked).
 */
const ANTIGRAVITY_TOOLS = [
  { name: "view_file", claude: ["Read"] },
  { name: "replace_file_content", claude: ["Edit", "Write"] },
  { name: "grep_search", claude: ["Grep"] },
  { name: "run_command", claude: ["Bash"] },
];

/**
 * The Antigravity custom agent format (`.agents/agents/<name>.md`): a name, a
 * description, the tools it may use and the role text. Antigravity gives an
 * agent no tools when the list is empty, so the list is always written: the
 * four documented tools for an agent whose source names none (as Claude Code
 * gives it every tool), else the ones that match the source's tools. Its model
 * and shell policy are left to Antigravity's defaults.
 *
 * @param {Agent} agent
 * @returns {string}
 */
export function renderAntigravity(agent) {
  const wanted = agent.tools;
  const tools = ANTIGRAVITY_TOOLS.filter(
    ({ claude }) => !wanted || claude.some((tool) => wanted.includes(tool)),
  ).map(({ name }) => name);
  if (tools.length === 0) {
    throw new Error(
      `${agent.name}: none of its tools has a documented Antigravity name`,
    );
  }
  return [
    "---",
    `name: ${JSON.stringify(agent.name)}`,
    `description: ${JSON.stringify(agent.description)}`,
    "tools:",
    ...tools.map((tool) => `  - ${tool}`),
    "---",
    "",
    `<!-- ${note(agent)} -->`,
    "",
    agent.body,
  ].join("\n");
}

/**
 * The Codex custom agent format: TOML with the role text as a literal string,
 * so backslashes and quotes in the text need no escaping.
 *
 * @param {Agent} agent
 * @returns {string}
 */
export function renderCodex(agent) {
  if (agent.body.includes("'''")) {
    throw new Error(
      `${agent.name}: the body cannot be written as a TOML literal string`,
    );
  }
  return [
    `# ${note(agent)}`,
    `name = ${JSON.stringify(agent.name)}`,
    `description = ${JSON.stringify(agent.description)}`,
    `developer_instructions = '''\n${agent.body}'''`,
    "",
  ].join("\n");
}

import type { tokens } from "@mapcairn/theme";

/** The shape of the theme contract, so a test can pass a changed copy. */
type Tokens = typeof tokens;

/**
 * The framework's variables paired with the token each one reads. The values
 * are references to the SDK's custom properties, never colours or lengths, so
 * the site follows the tokens and the reader's light or dark choice without a
 * second edit.
 */
function infimaMapping(
  source: Tokens,
): ReadonlyArray<readonly [string, string]> {
  const { color, radius, space, type } = source;
  return [
    ["--ifm-font-family-base", type.family],
    ["--ifm-font-family-monospace", type.familyMono],
    ["--ifm-line-height-base", type.body.lineHeight],
    ["--ifm-font-weight-normal", type.weight.regular],
    ["--ifm-font-weight-semibold", type.weight.semibold],
    ["--ifm-font-weight-bold", type.weight.semibold],
    ["--ifm-heading-font-weight", type.weight.semibold],
    ["--ifm-background-color", color.pageBackground],
    ["--ifm-background-surface-color", color.surfaceRaised],
    ["--ifm-font-color-base", color.text],
    ["--ifm-font-color-secondary", color.textMuted],
    ["--ifm-color-content", color.text],
    ["--ifm-color-content-secondary", color.textMuted],
    ["--ifm-color-primary", color.accent],
    ["--ifm-color-primary-dark", color.accent],
    ["--ifm-color-primary-darker", color.accent],
    ["--ifm-color-primary-darkest", color.accent],
    ["--ifm-color-primary-light", color.accent],
    ["--ifm-color-primary-lighter", color.accent],
    ["--ifm-color-primary-lightest", color.accent],
    ["--ifm-link-color", color.accent],
    ["--ifm-link-hover-color", color.accent],
    ["--ifm-hr-border-color", color.hairline],
    ["--ifm-toc-border-color", color.hairline],
    ["--ifm-table-border-color", color.hairline],
    ["--ifm-global-radius", radius.control],
    ["--ifm-code-border-radius", radius.inner],
    ["--ifm-global-spacing", space.md],
    ["--ifm-spacing-horizontal", space.md],
    ["--ifm-navbar-background-color", color.pageBackground],
    ["--ifm-footer-background-color", color.pageBackground],
    ["--ifm-footer-color", color.textMuted],
    ["--ifm-footer-link-color", color.text],
    ["--ifm-code-background", color.surfaceRaised],
    ["--ifm-pre-background", color.surfaceRaised],
  ];
}

/** One token reference, found by walking the contract. */
type Reference = readonly [path: readonly string[], value: string];

/** Every leaf of the contract with the path of keys that leads to it. */
function leaves(node: unknown, path: readonly string[] = []): Reference[] {
  if (typeof node === "string") {
    return [[path, node]];
  }
  return Object.entries(node as Record<string, unknown>).flatMap(
    ([key, child]) => leaves(child, [...path, key]),
  );
}

/** `color.surfaceRaised` becomes `--mc-color-surface-raised`. */
function aliasName(path: readonly string[]): string {
  const words = path.map((word) =>
    word.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`),
  );
  return `--mc-${words.join("-")}`;
}

/**
 * The selector the variables are written under. The framework sets its dark
 * values on `html[data-theme="dark"]`, so a plain `:root` rule would lose to it
 * in the dark theme; `html[data-theme]` ties with it and this file comes later.
 */
const SELECTOR = "html, html[data-theme]";

/**
 * The stylesheet that maps the documentation framework's variables onto the
 * SDK's tokens, and gives every token a stable alias (`--mc-color-accent`) for
 * the site's own rules. It is generated at build time from the exported
 * `tokens` object, because the token custom properties have generated names.
 * @param source - The theme contract. Defaults to the SDK's own.
 */
export function buildThemeCss(source: Tokens): string {
  return `/* Generated by scripts/generateTheme.ts from @mapcairn/theme. Do not edit. */\n${buildThemeRule(source, SELECTOR)}`;
}

/**
 * The rule that writes every alias and framework variable under a selector.
 * A variable that reads another is worked out where it is declared, so an
 * element that sets its own `data-theme` needs the rule again to read its own
 * theme's colours instead of the page's.
 * @param source - The theme contract.
 * @param selector - The selector the variables are written under.
 */
export function buildThemeRule(source: Tokens, selector: string): string {
  const aliases = leaves(source).map(
    ([path, value]) => [aliasName(path), value] as const,
  );
  const lines = [...aliases, ...infimaMapping(source)].map(
    ([name, value]) => `  ${name}: ${value};`,
  );
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

import type { tokenValues } from "@mapcairn/theme";

/** The syntax palette by theme, as `tokenValues.syntaxPalette` holds it. */
type Palette = typeof tokenValues.syntaxPalette;

/** `className` becomes `--mc-syntax-class-name`. */
function propertyName(role: string): string {
  return `--mc-syntax-${role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}`;
}

/** One rule: the selector and a custom property for each role. */
function block(selector: string, roles: Palette["light"]): string {
  const lines = Object.entries(roles).map(
    ([role, value]) => `  ${propertyName(role)}: ${value};`,
  );
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

/**
 * The stylesheet that gives each syntax role a custom property
 * (`--mc-syntax-keyword`) for the code blocks' token classes. The light values
 * sit on `html` and the dark ones on the framework's dark attribute, which it
 * always sets, so the reader's choice and the system's both reach the code.
 * The values are the SDK's own (`tokenValues.syntaxPalette`), so the contrast
 * its test checks is the contrast the page shows.
 * @param palette - The syntax colours. Defaults to the SDK's own at the call site.
 */
export function buildSyntaxCss(palette: Palette): string {
  return `/* Generated by scripts/generateTheme.ts from @mapcairn/theme. Do not edit. */\n${block("html", palette.light)}${block('html[data-theme="dark"]', palette.dark)}`;
}
